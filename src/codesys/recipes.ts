/**
 * Recipes as plain ST: a struct with one field per recipe variable, the recipes in a
 * RETAIN array (so values saved from the HMI survive a power cycle), their names, and a
 * program that applies a recipe to the live variables or stores the live values in one.
 * Generated code works on any controller and needs no library. (CODESYS's own Recipe
 * Manager can be created by script, but in the simulation its runtime never found the
 * recipes; checked on SP21.)
 */
import * as z from "zod/v4";
import type { ActionResult, RegisterAction } from "../actions.js";
import type { AppContext } from "../tools.js";
import { parseDeclaration } from "./decl.js";
import type { TreeNode } from "./st.js";

export const recipeSchema = z.object({
  name: z.string().regex(/^[A-Za-z][A-Za-z0-9_]*$/).describe("e.g. 'Pump': makes ST_Recipe_Pump, GVL_Recipe_Pump and PRG_Recipe_Pump"),
  variables: z
    .array(z.union([z.string(), z.object({ path: z.string(), type: z.string().optional() })]))
    .min(1)
    .describe("The variables a recipe sets, e.g. ['PLC_PRG.rSetpoint', {path: 'GVL.rSpeed', type: 'REAL'}]; the type is looked up when left out"),
  recipes: z.record(z.string().regex(/^[^'"$]{1,32}$/), z.record(z.string(), z.union([z.string(), z.number(), z.boolean()]))).describe("Recipe name -> { variable: value }, e.g. { Normal: { 'PLC_PRG.rSetpoint': 75 } }"),
});
export type RecipeSpec = z.infer<typeof recipeSchema>;

export interface RecipeCode {
  dut: { name: string; declaration: string };
  gvl: { name: string; declaration: string };
  program: { name: string; declaration: string; implementation: string };
  fields: { path: string; field: string; type: string }[];
}

/** An ST literal for a value of a type. */
function literal(v: string | number | boolean, type: string): string {
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (typeof v === "number") return /REAL/i.test(type) && Number.isInteger(v) ? `${v}.0` : String(v);
  if (/^W?STRING/i.test(type) && !/^'.*'$/.test(v)) return `'${v.replace(/'/g, "$$'")}'`;
  return v;
}

export function recipeCode(spec: RecipeSpec, types: Record<string, string>): RecipeCode {
  const n = spec.name;
  const used = new Set<string>();
  const fields = spec.variables.map((v) => {
    const path = typeof v === "string" ? v : v.path;
    const type = (typeof v === "string" ? undefined : v.type) ?? types[path];
    if (!type) throw new Error(`No type for ${path}: give it as {path: '${path}', type: 'REAL'}.`);
    let field = path.split(".").pop()!.replace(/\W/g, "_");
    for (let k = 2; used.has(field.toLowerCase()); k++) field = `${path.split(".").pop()!.replace(/\W/g, "_")}_${k}`;
    used.add(field.toLowerCase());
    return { path, field, type };
  });
  const names = Object.keys(spec.recipes);
  const count = names.length;
  for (const r of names) for (const p of Object.keys(spec.recipes[r]!)) if (!fields.some((f) => f.path === p)) throw new Error(`Recipe '${r}' sets ${p}, which isn't one of the variables.`);
  const init = names.map((r) => `(${fields.filter((f) => spec.recipes[r]![f.path] !== undefined).map((f) => `${f.field} := ${literal(spec.recipes[r]![f.path]!, f.type)}`).join(", ")})`);
  const dut = `ST_Recipe_${n}`, gvl = `GVL_Recipe_${n}`, prg = `PRG_Recipe_${n}`;
  return {
    fields,
    dut: { name: dut, declaration: `TYPE ${dut} :\nSTRUCT\n${fields.map((f) => `    ${f.field} : ${f.type}; // ${f.path}`).join("\n")}\nEND_STRUCT\nEND_TYPE` },
    gvl: {
      name: gvl,
      declaration: `// Recipes '${n}', generated by codesys-mcp-toolkit (create_recipes). RETAIN: values saved from the HMI survive a power cycle.\nVAR_GLOBAL RETAIN\n    aRecipes : ARRAY[0..${count - 1}] OF ${dut} := [${init.join(", ")}];\nEND_VAR\nVAR_GLOBAL CONSTANT\n    asNames : ARRAY[0..${count - 1}] OF STRING(32) := [${names.map((x) => `'${x}'`).join(", ")}];\n    iCount : INT := ${count};\nEND_VAR`,
    },
    program: {
      name: prg,
      // Through pointers: another POU may not write a program's local variables directly.
      declaration: `PROGRAM ${prg}\n// Set iApply to a recipe's index to write it to the variables; set iSave to store the variables in it.\nVAR\n    iApply : INT := -1;\n    iSave : INT := -1;\n    iActive : INT := -1; // the recipe applied last\n    sActive : STRING(32);\n${fields.map((f, k) => `    p${k} : POINTER TO ${f.type}; // ${f.path}`).join("\n")}\nEND_VAR`,
      implementation: [
        ...fields.map((f, k) => `p${k} := ADR(${f.path});`),
        `IF iApply >= 0 AND iApply < ${count} THEN`,
        ...fields.map((f, k) => `    p${k}^ := ${gvl}.aRecipes[iApply].${f.field};`),
        `    iActive := iApply;`,
        `    sActive := ${gvl}.asNames[iApply];`,
        `END_IF`,
        `iApply := -1;`,
        `IF iSave >= 0 AND iSave < ${count} THEN`,
        ...fields.map((f, k) => `    ${gvl}.aRecipes[iSave].${f.field} := p${k}^;`),
        `END_IF`,
        `iSave := -1;`,
      ].join("\n"),
    },
  };
}

/** Types of 'OWNER.name' variables from the exported declarations (only direct members). */
export function variableTypes(nodes: TreeNode[], paths: string[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (const p of paths) {
    const [owner, name, ...rest] = p.split(".");
    if (!owner || !name || rest.length) continue;
    const node = nodes.find((x) => x.name.toLowerCase() === owner.toLowerCase() && (x.kind === "pou" || x.kind === "gvl"));
    const v = node ? parseDeclaration(node.declaration).vars.find((x) => x.name.toLowerCase() === name.toLowerCase()) : undefined;
    if (v) out[p] = v.type;
  }
  return out;
}

export function registerRecipeAction(reg: RegisterAction, ctx: AppContext, run: (fn: () => Promise<string>) => Promise<ActionResult>): void {
  const b = ctx.bridge;
  reg(
    "create_recipes",
    {
      description:
        "Recipes for the machine's setpoints as generated ST: ST_Recipe_<name> (a field per variable), GVL_Recipe_<name> (the recipes in a RETAIN array, so values saved from the HMI survive a power cycle, and their names) and PRG_Recipe_<name>, added to MainTask: set iApply to a recipe's index to write it to the variables, iSave to store the current values in it; iActive and sActive tell which recipe was applied last. On an HMI screen, a widget {type: 'recipe', recipe: '<name>', recipes: [names]} shows them with Apply and Save buttons. Recreating replaces the generated objects.",
      inputSchema: recipeSchema,
    },
    async (spec) =>
      run(async () => {
        const paths = spec.variables.map((v) => (typeof v === "string" ? v : v.path));
        const nodes = (await b.call<{ nodes: TreeNode[] }>("export", {}, { timeoutMs: 120_000 })).nodes;
        const code = recipeCode(spec, variableTypes(nodes, paths));
        const exists = (name: string) => nodes.some((x) => x.name.toLowerCase() === name.toLowerCase());
        const put = async (kind: string, o: { name: string; declaration: string; implementation?: string }) => {
          if (exists(o.name)) await b.call("object.write", { path: o.name, declaration: o.declaration, ...(o.implementation ? { implementation: o.implementation } : {}) });
          else await b.call("object.create", { kind, name: o.name, declaration: o.declaration, ...(o.implementation ? { implementation: o.implementation } : {}) });
        };
        await put("dut", code.dut);
        await put("gvl", code.gvl);
        await put("program", code.program);
        let task = "";
        for (const t of ["MainTask", "Task"]) {
          try {
            await b.call("task.configure", { name: t, add_calls: [code.program.name], save: ctx.autosave });
            task = t;
            break;
          } catch {
            /* try the next */
          }
        }
        const names = Object.keys(spec.recipes);
        return [
          `Created recipes '${spec.name}': ${names.map((x, i) => `${i} ${x}`).join(", ")} over ${code.fields.map((f) => `${f.path} : ${f.type}`).join(", ")}.`,
          `${code.dut.name}, ${code.gvl.name} (RETAIN) and ${code.program.name}${task ? `, called from ${task}` : " (add it to a task with configure_task)"}.`,
          `Apply one: ${code.program.name}.iApply := <index>; store the current values: ${code.program.name}.iSave := <index>. HMI: {type: 'recipe', recipe: '${spec.name}', recipes: ${JSON.stringify(names)}}. Compile to check.`,
        ].join("\n");
      }),
  );
}
